#!/usr/bin/env node

import { createHash } from 'node:crypto'
import { mkdtempSync, mkdirSync, readFileSync, readdirSync, renameSync, rmSync, statSync, writeFileSync } from 'node:fs'
import { tmpdir } from 'node:os'
import { join, resolve } from 'node:path'
import { spawnSync } from 'node:child_process'

const archive = resolve(process.argv[2] || '')
if (!process.argv[2]) {
  console.error('Usage: node scripts/import-lzc-gallery.mjs /path/to/LZC.zip')
  process.exit(1)
}

const root = resolve(import.meta.dirname, '..')
const outputDir = join(root, 'frontend/public/inspiration/lz-archive')
const manifestPath = join(root, 'frontend/src/lzGallery.js')
const workDir = mkdtempSync(join(tmpdir(), 'lodex-lzc-'))
const stagedOutputDir = join(workDir, 'optimized')

const categoryRules = [
  ['Kitchens', /kitchen/i, 'Kitchen layouts, cabinetry, and finish combinations'],
  ['Cabinetry & wood', /cabinet|wood_species/i, 'Cabinet profiles, wood tones, and built-in details'],
  ['Bathrooms', /bathroom/i, 'Bathroom layouts, vanities, tile, and stone finishes'],
  ['Tile & patterns', /tile|geometric_pattern/i, 'Tile layouts, patterns, spacing, and surface ideas'],
  ['Commercial', /commercial_office|industrial_office|commercial_interior/i, 'Commercial interiors and durable workplace finishes'],
  ['Painting', /painting|spray_gun/i, 'Interior coating and commercial painting ideas'],
  ['Installation', /installers|installation_team/i, 'Measurement, delivery, fitting, and installation concepts'],
  ['Fabrication', /fabrication|CNC|measuring|warehouse|workshop/i, 'Stone fabrication, shop work, and precision processes'],
  ['Materials & surfaces', /granite|quartz|laminate|stone/i, 'Stone, laminate, wood, and countertop material ideas'],
]

const excluded = /Create_a_clean_modern_flat-icon|think_of_a_circle|FABRICATION_--profile/i
// Hand-curated from the deduplicated archive. The order is intentional: the first
// 12 are the strongest, most varied concepts and become the homepage preview.
const curatedOriginalIndices = [
  42, 46, 97, 124, 19, 30, 1, 110, 99, 22, 70, 126,
  2, 38, 43, 85, 47, 48, 98, 100, 125, 149, 151, 18,
  20, 83, 35, 115, 127, 136, 4, 5, 25, 94, 7, 8,
]
const run = (command, args) => {
  const result = spawnSync(command, args, { encoding: 'utf8' })
  if (result.status !== 0) throw new Error(result.stderr || `${command} failed`)
}

try {
  run('unzip', ['-q', archive, '-d', workDir])
  const files = readdirSync(workDir)
    .filter(file => file.toLowerCase().endsWith('.png') && !excluded.test(file))
    .sort((a, b) => a.localeCompare(b))

  const seen = new Set()
  const uniqueFiles = files.filter(file => {
    const hash = createHash('sha256').update(readFileSync(join(workDir, file))).digest('hex')
    if (seen.has(hash)) return false
    seen.add(hash)
    return true
  })

  mkdirSync(stagedOutputDir, { recursive: true })

  const curatedFiles = curatedOriginalIndices.map(originalIndex => {
    const file = uniqueFiles[originalIndex - 1]
    if (!file) throw new Error(`Curated image ${originalIndex} is missing from the deduplicated archive`)
    return { file, originalIndex }
  })

  const categoryCounts = new Map()
  const gallery = curatedFiles.map(({ file, originalIndex }) => {
    const [category, , detail] = categoryRules.find(([, matcher]) => matcher.test(file)) || ['Materials & surfaces', null, 'Material, finish, and surface inspiration']
    const categoryIndex = (categoryCounts.get(category) || 0) + 1
    categoryCounts.set(category, categoryIndex)
    const id = String(originalIndex).padStart(3, '0')
    const outputName = `lz-${id}.webp`
    const outputPath = join(stagedOutputDir, outputName)
    for (let attempt = 1; attempt <= 3; attempt += 1) {
      run('convert', [join(workDir, file), '-auto-orient', '-resize', '1200x1200>', '-strip', '-quality', '78', '-define', 'webp:method=6', outputPath])
      if (statSync(outputPath).size > 0) break
      rmSync(outputPath, { force: true })
      if (attempt === 3) throw new Error(`Image conversion produced an empty file after three attempts: ${file}`)
    }
    return {
      id: `lz-${id}`,
      src: `/inspiration/lz-archive/${outputName}`,
      title: `${category} inspiration ${String(categoryIndex).padStart(2, '0')}`,
      detail,
      category,
      alt: `AI-generated LZ Custom ${category.toLowerCase()} inspiration concept ${categoryIndex}`,
    }
  })

  const header = '// Generated by scripts/import-lzc-gallery.mjs from the curated, deduplicated LZ Custom archive.\n'
  rmSync(outputDir, { recursive: true, force: true })
  renameSync(stagedOutputDir, outputDir)
  writeFileSync(manifestPath, `${header}export const lzGalleryProjects = ${JSON.stringify(gallery, null, 2)}\n`)
  console.log(`Imported ${gallery.length} gallery images into ${outputDir}`)
} finally {
  rmSync(workDir, { recursive: true, force: true })
}
